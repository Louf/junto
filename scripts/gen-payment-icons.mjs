/**
 * Pulls payment brand glyph paths out of simple-icons into a checked-in file.
 *
 * Run: pnpm icons
 *
 * Why a generator rather than a runtime import: the method pickers are client
 * components, and importing simple-icons directly would ship the whole icon
 * set to the browser. This writes only the four paths we use.
 *
 * Anything simple-icons doesn't carry is left out, and PaymentIcon falls back
 * to a generic wallet glyph for it.
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const OUT = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "components",
  "paymentIconPaths.ts",
);

const EXPORTS = {
  venmo: "siVenmo",
  cashapp: "siCashApp",
  paypal: "siPaypal",
  zelle: "siZelle",
};

const icons = await import("simple-icons");

const found = {};
const missing = [];

for (const [method, exportName] of Object.entries(EXPORTS)) {
  // simple-icons has renamed exports across majors; try a couple of casings
  // before giving up on a brand.
  const candidates = [
    exportName,
    exportName.toLowerCase(),
    `si${method.charAt(0).toUpperCase()}${method.slice(1)}`,
  ];
  const hit = candidates.map((c) => icons[c]).find((i) => i?.path);

  if (hit) found[method] = hit.path;
  else missing.push(method);
}

const body = `/**
 * Brand glyph paths, generated by scripts/gen-payment-icons.mjs.
 * Do not edit by hand — run \`pnpm icons\` to regenerate.
 *
 * Paths come from Simple Icons (CC0). The trademarks remain the property of
 * their respective owners; these are used nominatively to indicate which
 * service a payment is sent through, always alongside a text label.
 */
export const PAYMENT_ICON_PATHS: Record<string, string> = {
${Object.entries(found)
  .map(([k, v]) => `  ${k}: "${v}",`)
  .join("\n")}
};

/** Simple Icons uses a 24x24 canvas. */
export const PAYMENT_ICON_VIEWBOX = "0 0 24 24";
`;

await writeFile(OUT, body, "utf8");

console.log(`Wrote ${Object.keys(found).length} icon(s) to ${OUT}`);
if (missing.length) {
  console.log(
    `No simple-icons entry for: ${missing.join(", ")} — these fall back to the generic wallet glyph.`,
  );
}
